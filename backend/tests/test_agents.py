"""
Agent behavior tests: tool call counts, context storage, no memory leaks,
web routing correctness, parallel tool call race condition fix.
"""
import asyncio
import pytest
from app.agents.orchestrator import OrchestratorAgent


def make_orchestrator(settings, pinecone_index, policy_id, mode="hybrid_rerank"):
    return OrchestratorAgent(
        policy_id=policy_id,
        pinecone_index=pinecone_index,
        cohere_api_key=settings.cohere_api_key,
        anthropic_api_key=settings.anthropic_api_key,
        data_dir=settings.data_dir,
        retrieval_mode=mode,
        top_k=5,
        candidate_k=20,
        model=settings.eval_model,  # use Haiku for tests to reduce cost
    )


async def run_question(orchestrator, question):
    response = ""
    retrieval_log = []
    web_fetch_status = "not_triggered"
    input_tokens = 0
    output_tokens = 0
    async for event in orchestrator.stream_chat(question, conversation_history=[]):
        if event.get("type") == "chunk":
            response += event.get("content", "")
        elif event.get("type") == "done":
            retrieval_log = event.get("retrieval_log", [])
            web_fetch_status = event.get("web_fetch_status", "not_triggered")
            input_tokens = event.get("input_tokens", 0)
            output_tokens = event.get("output_tokens", 0)
    return response, retrieval_log, web_fetch_status, input_tokens, output_tokens


# ── Basic response quality ─────────────────────────────────────────────────────

@pytest.mark.asyncio
async def test_orchestrator_returns_non_empty_response(settings, pinecone_index, policy_id):
    orch = make_orchestrator(settings, pinecone_index, policy_id)
    response, _, _, _, _ = await run_question(orch, "What is the waiting period for maternity?")
    assert len(response) > 100, f"Response too short: {response[:100]}"


