# ── Parallel tool call race condition ──────────────────────────────────────────

@pytest.mark.asyncio
async def test_parallel_retrieve_log_entries_all_have_result_full(settings, pinecone_index, policy_id):
    """
    Regression: when LLM calls retrieve_from_policy twice in parallel,
    log[-1] race condition caused one entry to lose result_full.
    Fixed by using log[entry_idx] instead of log[-1].
    """
    orch = make_orchestrator(settings, pinecone_index, policy_id, mode="dense_rerank")
    _, retrieval_log, _, _, _ = await run_question(
        orch, "What is the waiting period for maternity?"
    )
    retrieve_entries = [e for e in retrieval_log if e.get("tool") == "retrieve_from_policy"]
    for i, entry in enumerate(retrieve_entries):
        assert "result_full" in entry, \
            f"Entry {i} of {len(retrieve_entries)} missing result_full — race condition bug still present"


# ── No 400 errors from memory accumulation ────────────────────────────────────

@pytest.mark.asyncio
async def test_fresh_agent_per_question_no_memory_leak(settings, pinecone_index, policy_id):
    """
    Regression: reusing one agent across 12+ questions caused 400 errors
    from accumulated conversation memory. Each question must get a fresh agent.
    """
    questions = [
        "What is the initial waiting period?",
        "Is maternity covered?",
        "What is the room rent sub-limit?",
    ]
    for q in questions:
        orch = make_orchestrator(settings, pinecone_index, policy_id)
        response, _, _, _, _ = await run_question(orch, q)
        assert not response.startswith("ERROR:"), \
            f"Got error on question '{q}': {response[:100]}"
        assert len(response) > 50, f"Empty response for '{q}'"
