# ── Context storage ────────────────────────────────────────────────────────────

@pytest.mark.asyncio
async def test_retrieval_log_has_retrieve_entry(settings, pinecone_index, policy_id):
    orch = make_orchestrator(settings, pinecone_index, policy_id)
    _, retrieval_log, _, _, _ = await run_question(orch, "What is the waiting period for maternity?")
    retrieve_entries = [e for e in retrieval_log if e.get("tool") == "retrieve_from_policy"]
    assert len(retrieve_entries) >= 1, \
        f"retrieve_from_policy not called. Log: {retrieval_log}"


@pytest.mark.asyncio
async def test_retrieval_log_has_result_full(settings, pinecone_index, policy_id):
    """Critical: result_full must be present — this was the bug that caused garbage Ragas scores."""
    orch = make_orchestrator(settings, pinecone_index, policy_id)
    _, retrieval_log, _, _, _ = await run_question(orch, "What is the waiting period for maternity?")
    retrieve_entries = [e for e in retrieval_log if e.get("tool") == "retrieve_from_policy"]
    for entry in retrieve_entries:
        assert "result_full" in entry, \
            "retrieve_from_policy log entry missing result_full — context will be empty in eval"
        assert len(entry["result_full"]) > 50, \
            f"result_full too short ({len(entry['result_full'])} chars) — may be empty context"


@pytest.mark.asyncio
async def test_retrieval_log_cleared_between_calls(settings, pinecone_index, policy_id):
    """Verify no memory leak between questions — each call gets a fresh log."""
    orch = make_orchestrator(settings, pinecone_index, policy_id)
    _, log1, _, _, _ = await run_question(orch, "What is the waiting period for maternity?")
    _, log2, _, _, _ = await run_question(orch, "Is cataract covered after 18 months?")
    # log2 should not contain entries from log1
    log2_queries = [e.get("query", "") for e in log2]
    assert not any("maternity" in q.lower() for q in log2_queries), \
        "retrieval_log was not cleared between calls — memory leak detected"


